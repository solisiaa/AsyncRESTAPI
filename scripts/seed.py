"""Seed demo data: users, projects, tasks."""

from __future__ import annotations

import asyncio
import random
from datetime import datetime, timedelta, timezone

from app.core.config import get_settings
from app.core.security import get_password_hash
from app.models.project import Project
from app.models.task import Task
from app.models.user import User
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine


async def main() -> None:
    """Insert demo users/projects/tasks (idempotent by e-mail)."""
    settings = get_settings()
    engine = create_async_engine(settings.database_url)
    factory = async_sessionmaker(engine, expire_on_commit=False)
    async with factory() as session:
        existing = await session.get(User, 1)
        if existing is not None:
            print("Seed already applied (user id=1 exists).")
            await engine.dispose()
            return
        admin = User(
            email="admin@example.com",
            username="admin",
            hashed_password=get_password_hash("admin12345"),
            role="admin",
        )
        manager = User(
            email="manager@example.com",
            username="manager",
            hashed_password=get_password_hash("manager12345"),
            role="manager",
        )
        user = User(
            email="user@example.com",
            username="user",
            hashed_password=get_password_hash("user12345"),
            role="user",
        )
        session.add_all([admin, manager, user])
        await session.flush()

        projects: list[Project] = []
        for i in range(3):
            p = Project(
                name=f"Demo project {i + 1}",
                description=f"Seeded project #{i + 1}",
                status="active",
                owner_id=manager.id,
            )
            session.add(p)
            projects.append(p)
        await session.flush()

        now = datetime.now(timezone.utc)
        statuses = ["todo", "in_progress", "done"]
        priorities = ["low", "medium", "high"]
        for i in range(30):
            proj = random.choice(projects)
            st = random.choice(statuses)
            created = now - timedelta(days=random.randint(0, 60))
            closed = (created + timedelta(hours=random.randint(1, 200))) if st == "done" else None
            if closed is not None and closed > now:
                closed = now
            t = Task(
                project_id=proj.id,
                title=f"Seed task {i + 1}",
                description="Generated by scripts/seed.py",
                status=st,
                priority=random.choice(priorities),
                assignee_id=random.choice([user.id, manager.id]),
                due_date=now + timedelta(days=random.randint(-10, 10)),
                created_at=created,
                closed_at=closed,
            )
            session.add(t)
        await session.commit()
        print("Seed done: 3 users, 3 projects, 30 tasks.")
    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
